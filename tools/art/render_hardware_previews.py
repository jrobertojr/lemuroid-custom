"""Bake lightweight front-view media templates with transparent dynamic-label apertures.
Blender -b --python tools/art/render_hardware_previews.py
This reads the editable .blend without changing it. No source game artwork is included.
"""
import bpy,json,math
from pathlib import Path
from mathutils import Vector
from bpy_extras.object_utils import world_to_camera_view
root=Path(__file__).resolve().parents[2]
bpy.ops.wm.open_mainfile(filepath=str(root/'art-source/faithful-hardware/hardware-library.blend'))
manifest=json.loads((root/'art-source/faithful-hardware/manifest.json').read_text(encoding='utf-8'))
output=root/'lemuroid-app/src/main/assets/media_previews';output.mkdir(exist_ok=True)
hold=bpy.data.materials.new('Dynamic label aperture');hold.use_nodes=True
nodes=hold.node_tree.nodes;nodes.clear();shader=nodes.new('ShaderNodeHoldout');surface=nodes.new('ShaderNodeOutputMaterial');hold.node_tree.links.new(shader.outputs[0],surface.inputs[0])
specs={}
for row in manifest['assets']:
    key=row['key']
    if not key.startswith('media_'):continue
    scene=bpy.data.scenes[key];bpy.context.window.scene=scene
    scene.render.resolution_x=256;scene.render.resolution_y=256;scene.render.resolution_percentage=100
    meshes=[o for o in scene.objects if o.type=='MESH']
    points=[o.matrix_world@v.co for o in meshes for v in o.data.vertices]
    low=[min(p[i] for p in points) for i in range(3)];high=[max(p[i] for p in points) for i in range(3)]
    center=Vector([(a+b)/2 for a,b in zip(low,high)])
    bpy.ops.object.camera_add(location=(center.x,low[1]-4,center.z));cam=bpy.context.object
    cam.rotation_euler=(center-cam.location).to_track_quat('-Z','Y').to_euler()
    cam.data.type='ORTHO';cam.data.ortho_scale=max(high[0]-low[0],high[2]-low[2])*1.14;scene.camera=cam
    bpy.context.view_layer.update()
    cover=[o for o in meshes if o.data.materials[0].name.startswith('cover')]
    projected=[world_to_camera_view(scene,cam,o.matrix_world@v.co) for o in cover for v in o.data.vertices]
    assert projected,key
    rect=[min(p.x for p in projected),1-max(p.y for p in projected),max(p.x for p in projected),1-min(p.y for p in projected)]
    assert all(0<=v<=1 for v in rect),(key,rect)
    specs[key.removeprefix('media_')]=dict(bounds=rect,ring=key in ['media_psx','media_segacd','media_psp'])
    for o in cover:o.data.materials[0]=hold
    world=bpy.data.worlds.new(key+' preview world');world.use_nodes=True
    world.node_tree.nodes['Background'].inputs[0].default_value=(.35,.35,.35,1);world.node_tree.nodes['Background'].inputs[1].default_value=.7;scene.world=world
    for loc,power in [((center.x-2,low[1]-3,center.z+3),140),((center.x+2,low[1]-2,center.z+1),70)]:
        bpy.ops.object.light_add(type='AREA',location=loc);light=bpy.context.object;light.data.energy=power;light.data.size=4
        light.rotation_euler=(center-light.location).to_track_quat('-Z','Y').to_euler()
    scene.render.engine='CYCLES';scene.cycles.samples=8;scene.cycles.use_denoising=True
    scene.render.film_transparent=True;scene.render.image_settings.file_format='PNG';scene.render.image_settings.color_mode='RGBA'
    scene.render.resolution_x=256;scene.render.resolution_y=256;scene.render.resolution_percentage=100
    scene.view_settings.view_transform='Standard';scene.render.filepath=str(output/(key.removeprefix('media_')+'.png'))
    bpy.ops.render.render(write_still=True)
    print('PREVIEW',key,flush=True)
(root/'art-source/faithful-hardware/preview-bounds.json').write_text(json.dumps(specs,indent=2)+'\n',encoding='utf-8')
code=['package com.swordfish.lemuroid.app.mobile.shared.compose.ui','', '// Generated by tools/art/render_hardware_previews.py; normalized front orthographic label bounds.',
      'internal data class MediaPreviewSpec(val left: Float, val top: Float, val right: Float, val bottom: Float, val ring: Boolean = false)',
      'internal object MediaPreviewGeometry {','    val bySystem = mapOf(']
for key,row in specs.items():
    values=', '.join(f'{v:.6f}f' for v in row['bounds']);ring=', ring = true' if row['ring'] else ''
    code.append(f'        "{key}" to MediaPreviewSpec({values}{ring}),')
code+=['    )','}','']
(root/'lemuroid-app/src/main/java/com/swordfish/lemuroid/app/mobile/shared/compose/ui/MediaPreviewGeometry.kt').write_text('\n'.join(code),encoding='utf-8')
print('PREVIEWS_READY',len(specs))
